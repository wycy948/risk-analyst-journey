# 运算符：加+  减-  乘*  除/  整除//  取余%  幂指数**

print('10+3=',10+3)
print('10-3=',10-3)
print('10*3=',10*3)
print('10/3=',10/3)
print('10//3=',10//3)
print('10%3=',10%3)
print('10**3=',10**3)

# 运算符的优先级------> ** --->* / // % ---> + -
print('10+3/2**3=',10+3/2**3) #--->2**3--->3/2**3-->10+3/2**3--->10.375

# 案例：输入两个数x,y,输出x+y和x-y
x=float(input('请输入x:'))
y=float(input('请输入y:'))

# x=0.2,y=0.1,x+y= 0.30000000000000004属于--->精度损失
print('x+y=',x+y)
print('x-y=',x-y)