# 赋值运算符 ---> = += -= /= *= %= //= **=
# print(num += 5)---> 这种写法是错误的，赋值运算不可以出现在里面

num = 10

num += 5
print('num += 5后，num= ',num)

num -= 5
print('num -= 5后，num= ',num)

num *= 5
print('num *=5后，num= ',num)

num /= 5
print('num /=5后，num= ',num)

num //= 5
print('num //= 5后，num= ',num)

num %= 5
print('num %= 5后，num= ',num)

num **= 5
print('num **= 5后，num= ',num)